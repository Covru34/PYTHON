# while - цикл з передумовою
# # для роботи циклу умова має бути вірною (True)
i = 0
count = int(input("Введіть кількість привітаннь з новим роком: "))
while i < count: # умова виконання циклу
    print("З Новим рокомНехай він принесе здоров’я, радість, мир і здійснення всіх мрій.Щастя та удачі у кожному дні!")# виведення поточного значення лічильника
    i += 1 #i=i+1 змінуює ітерації циклу - збільшення лічильника на 1